# P5a (CertBound): M5-1 gain-split table (descriptive, post-read; for the SI).  v1.1 (实验管理): signed values with |x| < 0.0005 are printed with 4 decimals (so a lower end such as -0.0004 keeps its sign), all others with 3; v1 5bca38b2 kept, its outputs renamed NOT_USED_.  WRITTEN, NOT RUN, until 实验管理 reviews it.
# Reads ONLY results_master.json of the tree (master sha pinned).  Per development site (BBBC-ALL, MP-IDB, Lacuna-B):
#   total sensitivity gain A2 - A0 (m51/result|M3|sites|<s>|mean_diff, with its seed-bootstrap lower end lower95_seed_bootstrap);
#   critical-value step A1 - A0 (m51x/sites|<s>|sens_A1_minus_A0|mean, boot95|0, boot95|1);
#   sampling step A2 - A1 (m51x/sites|<s>|sens_A2_minus_A1|mean, boot95|0/1) and the number of the 5 seeds with A2 - A1 > 0 (counted from per_seed|0..4);
#   half-width ratios at the fixed reference threshold: A2 / A0 (m51/result|M2|sites|<s>|ratio_A2_over_A0) and A2 / A1 (m51x/sites|<s>|hw_ratio_A2_over_A1|pooled, boot95|0/1).
# Caption text is NOT written here (the writing session writes it); the table notes only give units and the seed-bootstrap caveat (5 seeds: coarse intervals).
# Output (into <tree>/tables, 'x' mode): tab_m51_split.tex, tab_m51_split_numbers.json.
# v1.2 (实验管理): column heads B/N/U instead of A0/A1/A2; master pin b5faa828; output to --out (new dir).
# Usage: python3 -B make_tab_m51split.py --tree <tree_bj_v1_...> --out <new dir>
import argparse, hashlib, json, sys
from pathlib import Path
MASTER_SHA = "b5faa82817383bc977e03617e6e85e53ad15b9347a079d06dc55d19f585ac04d"   # v1.2: current master (add-only since 58f900ee; the m51 / m51x keys read here are unchanged)
SITES = (("bbbc041_all", "BBBC-ALL"), ("mpidb_full", "MP-IDB"), ("lacuna_B", "Lacuna-B"))


def sha(p):
    with open(p, "rb") as fh: return hashlib.sha256(fh.read()).hexdigest()


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--tree", required=True); ap.add_argument("--out", required=True); a = ap.parse_args(); tree = Path(a.tree); rm = tree / "results_master.json"   # v1.2: --out (new dir) instead of <tree>/tables
    if sha(rm) != MASTER_SHA: print("GATE (exit 3): results_master sha differs", file=sys.stderr); return 3
    v = json.load(open(rm))["values"]
    if Path(a.out).exists(): print("GATE (exit 3): output dir exists", file=sys.stderr); return 3
    outs = [Path(a.out) / n for n in ("tab_m51_split.tex", "tab_m51_split_numbers.json")]
    f3 = lambda x: (f"{x:+.4f}" if abs(x) < 0.0005 else f"{x:+.3f}"); f2 = lambda x: f"{x:.2f}"; rows = []; numbers = {}
    for s, name in SITES:
        k = lambda key: v[key]
        tot = k(f"m51/result|M3|sites|{s}|mean_diff"); tot_lo = k(f"m51/result|M3|sites|{s}|lower95_seed_bootstrap")
        a10 = k(f"m51x/sites|{s}|sens_A1_minus_A0|mean"); a10_ci = (k(f"m51x/sites|{s}|sens_A1_minus_A0|boot95|0"), k(f"m51x/sites|{s}|sens_A1_minus_A0|boot95|1"))
        a21 = k(f"m51x/sites|{s}|sens_A2_minus_A1|mean"); a21_ci = (k(f"m51x/sites|{s}|sens_A2_minus_A1|boot95|0"), k(f"m51x/sites|{s}|sens_A2_minus_A1|boot95|1"))
        npos = sum(k(f"m51x/sites|{s}|sens_A2_minus_A1|per_seed|{i}") > 0 for i in range(5))
        r20 = k(f"m51/result|M2|sites|{s}|ratio_A2_over_A0"); r21 = k(f"m51x/sites|{s}|hw_ratio_A2_over_A1|pooled"); r21_ci = (k(f"m51x/sites|{s}|hw_ratio_A2_over_A1|boot95|0"), k(f"m51x/sites|{s}|hw_ratio_A2_over_A1|boot95|1"))
        numbers[s] = dict(total_A2_minus_A0=tot, total_lower95=tot_lo, A1_minus_A0=a10, A1_minus_A0_ci=a10_ci, A2_minus_A1=a21, A2_minus_A1_ci=a21_ci, n_seeds_A2_minus_A1_pos=int(npos), hw_A2_over_A0=r20, hw_A2_over_A1=r21, hw_A2_over_A1_ci=r21_ci)
        rows.append(f"{name} & {f3(tot)} ({f3(tot_lo)}) & {f3(a10)} [{f3(a10_ci[0])}, {f3(a10_ci[1])}] & {f3(a21)} [{f3(a21_ci[0])}, {f3(a21_ci[1])}] & {npos}/5 & {f2(r20)} & {f2(r21)} [{f2(r21_ci[0])}, {f2(r21_ci[1])}] \\\\")
    tex = "\n".join([
        "% generated by make_tab_m51split.py from results_master " + MASTER_SHA[:8] + "; do not edit by hand",
        "\\begin{tabular}{lcccccc}", "\\toprule",
        " & \\multicolumn{4}{c}{Sensitivity difference} & \\multicolumn{2}{c}{Half-width ratio} \\\\",
        "\\cmidrule(lr){2-5}\\cmidrule(lr){6-7}",
        # v1.2: codes A0/A1/A2 -> B/N/U as defined in the caption (2b7c58c9)
        "Site & U $-$ B (lower end) & N $-$ B [95\\%] & U $-$ N [95\\%] & U $>$ N & U/B & U/N [95\\%] \\\\", "\\midrule", *rows, "\\bottomrule", "\\end{tabular}", ""])
    Path(a.out).mkdir(parents=True)
    with open(outs[0], "x") as fh: fh.write(tex)
    with open(outs[1], "x") as fh: json.dump(dict(master_sha256=MASTER_SHA, script_sha256=sha(__file__), numbers=numbers), fh, indent=1)
    print({o.name: sha(o) for o in outs}); print(tex); return 0


if __name__ == "__main__": sys.exit(main())
